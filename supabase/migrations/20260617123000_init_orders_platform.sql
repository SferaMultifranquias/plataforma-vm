create or replace function public.approve_order(p_order_id uuid)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders;
begin
  if not public.is_admin() then
    raise exception 'Only admins can approve orders';
  end if;

  select * into v_order
  from public.orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'Order not found';
  end if;

  if v_order.status <> 'PENDING_APPROVAL' then
    raise exception 'Order is not pending approval';
  end if;

  update public.orders
  set
    status = 'APPROVED',
    approved_by_id = auth.uid(),
    approved_at = now(),
    rejection_reason = null
  where id = p_order_id
  returning * into v_order;

  insert into public.audit_logs (user_id, action, entity, entity_id, previous_data, new_data)
  values (auth.uid(), 'ORDER_APPROVED', 'orders', v_order.id, null, to_jsonb(v_order));

  return v_order;
end;
$$;

create or replace function public.reject_order(p_order_id uuid, p_reason text)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders;
begin
  if not public.is_admin() then
    raise exception 'Only admins can reject orders';
  end if;

  if coalesce(trim(p_reason), '') = '' then
    raise exception 'Rejection reason is required';
  end if;

  select * into v_order
  from public.orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'Order not found';
  end if;

  if v_order.status <> 'PENDING_APPROVAL' then
    raise exception 'Order is not pending approval';
  end if;

  update public.orders
  set
    status = 'REJECTED',
    approved_by_id = auth.uid(),
    rejected_at = now(),
    rejection_reason = p_reason
  where id = p_order_id
  returning * into v_order;

  insert into public.audit_logs (user_id, action, entity, entity_id, previous_data, new_data)
  values (auth.uid(), 'ORDER_REJECTED', 'orders', v_order.id, null, to_jsonb(v_order));

  return v_order;
end;
$$;


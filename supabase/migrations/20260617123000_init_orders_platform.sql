create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, name, email, role, is_active)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1)),
    new.email,
    coalesce(upper(new.raw_user_meta_data ->> 'role'), 'USER'),
    true
  )
  on conflict (id) do update
  set
    name = excluded.name,
    email = excluded.email,
    role = case
      when public.profiles.role = 'ADMIN' then public.profiles.role
      else excluded.role
    end,
    updated_at = now();

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.generate_order_internal_number()
returns text
language plpgsql
as $$
declare
  next_number bigint;
begin
  select count(*) + 1 into next_number from public.orders;
  return 'ORD-' || to_char(current_date, 'YYYYMMDD') || '-' || lpad(next_number::text, 4, '0');
end;
$$;

create or replace function public.log_order_status_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.status_history (order_id, previous_status, new_status, changed_by_id, comment)
    values (new.id, null, new.status, coalesce(auth.uid(), new.requester_id), 'Order created');
  elsif old.status is distinct from new.status then
    insert into public.status_history (order_id, previous_status, new_status, changed_by_id, comment)
    values (new.id, old.status, new.status, coalesce(auth.uid(), new.requester_id), null);
  end if;
  return new;
end;
$$;

drop trigger if exists trg_orders_status_history on public.orders;
create trigger trg_orders_status_history
after insert or update on public.orders
for each row execute function public.log_order_status_change();

create or replace function public.create_order(
  p_brand text,
  p_store text,
  p_cost_center text,
  p_purpose text,
  p_justification text,
  p_priority text,
  p_notes text default null
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders;
begin
  insert into public.orders (
    internal_number,
    requester_id,
    brand,
    store,
    cost_center,
    purpose,
    justification,
    priority,
    notes
  )
  values (
    public.generate_order_internal_number(),
    auth.uid(),
    p_brand,
    p_store,
    p_cost_center,
    p_purpose,
    p_justification,
    p_priority,
    p_notes
  )
  returning * into v_order;

  insert into public.audit_logs (user_id, action, entity, entity_id, new_data)
  values (auth.uid(), 'ORDER_CREATED', 'orders', v_order.id, to_jsonb(v_order));

  return v_order;
end;
$$;

create or replace function public.submit_order(p_order_id uuid)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders;
begin
  select * into v_order
  from public.orders
  where id = p_order_id
    and requester_id = auth.uid()
  for update;

  if not found then
    raise exception 'Order not found';
  end if;

  if v_order.status not in ('DRAFT', 'REJECTED') then
    raise exception 'Only draft or rejected orders can be submitted';
  end if;

  update public.orders
  set
    status = 'PENDING_APPROVAL',
    submitted_at = now(),
    rejection_reason = null
  where id = p_order_id
  returning * into v_order;

  insert into public.audit_logs (user_id, action, entity, entity_id, previous_data, new_data)
  values (auth.uid(), 'ORDER_SUBMITTED', 'orders', v_order.id, null, to_jsonb(v_order));

  return v_order;
end;
$$;

